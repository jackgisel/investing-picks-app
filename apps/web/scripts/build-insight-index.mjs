/**
 * Generates src/lib/insight-index.ts from src/content/insights/*.tsx.
 *
 *   node scripts/build-insight-index.mjs           # rewrite the index
 *   node scripts/build-insight-index.mjs --check   # fail if it is stale
 *
 * Why the index exists at all: each insight module statically imports the
 * whole prose component set and ships its full article body, and lib/insights
 * imports every one of them. Any client component that touches lib/insights
 * therefore pulls every article into its bundle. The dashboard needs insight
 * *metadata* on pages that are all "use client", so it reads this file — plain
 * data, no ComponentType, no article bodies.
 *
 * Generated rather than hand-maintained because the file it replaces
 * (lib/insight-links.ts) was hand-maintained and its comment already had to
 * ask people to keep two lists in sync.
 */
import { readFileSync, writeFileSync, readdirSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const here = dirname(fileURLToPath(import.meta.url));
const contentDir = join(here, "..", "src", "content", "insights");
const outFile = join(here, "..", "src", "lib", "insight-index.ts");

/**
 * Pulls the `meta: { ... }` literal out of a module and evaluates it.
 *
 * The metadata is authored as a plain object literal with no computed values,
 * so this stays a parse rather than an execution of app code.
 */
function readMeta(file) {
  const src = readFileSync(join(contentDir, file), "utf8");
  const start = src.indexOf("meta: {");
  if (start === -1) throw new Error(`${file}: no meta block`);

  // Walk braces to find the end of the literal — the values contain commas,
  // apostrophes and nested arrays, so a regex would not survive them.
  let depth = 0;
  let end = -1;
  for (let i = src.indexOf("{", start); i < src.length; i++) {
    if (src[i] === "{") depth++;
    else if (src[i] === "}") {
      depth--;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  if (end === -1) throw new Error(`${file}: unterminated meta block`);

  const literal = src.slice(src.indexOf("{", start), end);
  const meta = new Function(`return (${literal});`)();

  if (meta.slug !== file.replace(/\.tsx$/, "")) {
    throw new Error(
      `${file}: slug "${meta.slug}" does not match its filename. The route ` +
        `is built from the slug, so the two must agree.`,
    );
  }
  return meta;
}

const metas = readdirSync(contentDir)
  .filter((f) => f.endsWith(".tsx"))
  .map(readMeta)
  .sort(
    (a, b) =>
      b.publishedAt.localeCompare(a.publishedAt) ||
      (a.ticker ?? "").localeCompare(b.ticker ?? ""),
  );

const rows = metas
  .map((m) =>
    [
      "  {",
      `    slug: ${JSON.stringify(m.slug)},`,
      `    title: ${JSON.stringify(m.title)},`,
      `    description: ${JSON.stringify(m.description)},`,
      `    ticker: ${JSON.stringify(m.ticker ?? null)},`,
      `    postType: ${JSON.stringify(m.postType)},`,
      `    publishedAt: ${JSON.stringify(m.publishedAt)},`,
      `    readingTime: ${m.readingTime},`,
      "  },",
    ].join("\n"),
  )
  .join("\n");

const output = `// GENERATED by scripts/build-insight-index.mjs — do not edit by hand.
// Regenerate after adding or changing an insight:
//   node scripts/build-insight-index.mjs

/**
 * Insight metadata, safe to import from client components.
 *
 * lib/insights.ts statically imports every article module, so importing it
 * from a "use client" file ships every article body in that page's bundle.
 * The dashboard is entirely client components and only ever needs the
 * metadata, so it reads this instead. Sorted newest first.
 */
export interface InsightIndexEntry {
  slug: string;
  title: string;
  description: string;
  ticker: string | null;
  postType: "pick" | "quarterly_review";
  publishedAt: string;
  readingTime: number;
}

export const INSIGHT_INDEX: readonly InsightIndexEntry[] = [
${rows}
];

/**
 * The insight covering a ticker, if we have published one.
 *
 * Tolerates a null ticker: the anonymised payload served to non-subscribers
 * has no tickers, and it arrives as a 200 on the ordinary success path.
 */
export function getInsightByTicker(
  ticker: string | null | undefined,
): InsightIndexEntry | undefined {
  if (!ticker) return undefined;
  const upper = ticker.toUpperCase();
  return INSIGHT_INDEX.find(
    (i) => i.postType === "pick" && i.ticker?.toUpperCase() === upper,
  );
}

/** Insights covering any of these tickers, newest first. */
export function getInsightsForTickers(
  tickers: readonly (string | null | undefined)[],
): InsightIndexEntry[] {
  const wanted = new Set(
    tickers.filter((t): t is string => Boolean(t)).map((t) => t.toUpperCase()),
  );
  return INSIGHT_INDEX.filter(
    (i) => i.ticker !== null && wanted.has(i.ticker.toUpperCase()),
  );
}
`;

const existing = (() => {
  try {
    return readFileSync(outFile, "utf8");
  } catch {
    return null;
  }
})();

if (process.argv.includes("--check")) {
  if (existing !== output) {
    console.error(
      "insight-index.ts is stale. Run: node scripts/build-insight-index.mjs",
    );
    process.exit(1);
  }
  console.log(`insight index: ok — ${metas.length} insights`);
} else {
  writeFileSync(outFile, output);
  console.log(`insight index: wrote ${metas.length} insights to ${outFile}`);
}
